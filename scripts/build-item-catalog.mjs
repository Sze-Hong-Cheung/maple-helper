/**
 * Items whose star ceiling is lower than their level would imply. The wiki
 * lists these as explicit exceptions to the level-based cap.
 */
const STAR_CAP_OVERRIDES = {
  'Sengoku Hakase Badge': 22,
  'Ghost Ship Exorcist': 22,
  'Sweetwater Shoes': 15,
  'Sweetwater Gloves': 15,
  'Sweetwater Cape': 15,
}

async function findItem(name) {
  const url = `${API}?searchFor=${encodeURIComponent(name)}&overallCategoryFilter=Equip&count=60`
  const res = await fetch(url)
  if (!res.ok) throw new Error(`search "${name}" failed: HTTP ${res.status}`)

  const hits = await res.json()
  const exact = hits.filter((hit) => hit.name === name)
  if (exact.length === 0) {
    throw new Error(`no exact match for "${name}" (${hits.length} loose hits)`)
  }

  // Several ids share a name (per-class or per-gender copies); the lowest id is
  // the canonical one and its icon is the one players recognise.
  exact.sort((a, b) => a.id - b.id)
  const item = exact[0]

  return {
    id: item.id,
    name: item.name,
    level: item.requiredLevel,
    slot: item.typeInfo?.subCategory ?? item.typeInfo?.category ?? 'Equip',
    maxStar: STAR_CAP_OVERRIDES[item.name],
  }
}

async function downloadIcon(id) {
  const res = await fetch(`${API}/${id}/icon`)
  if (!res.ok) throw new Error(`icon ${id} failed: HTTP ${res.status}`)
  await writeFile(resolve(ICON_DIR, `${id}.png`), Buffer.from(await res.arrayBuffer()))
}

function emitModule(groups) {
  const lines = [
    '// Generated by scripts/build-item-catalog.mjs - do not edit by hand.',
    `// Source: maplestory.io ${REGION} v${VERSION}. Levels are the in-game`,
    '// required levels, which is the only item property Star Force math needs.',
    '',
    "const icons = import.meta.glob('../assets/items/*.png', {",
    '  eager: true,',
    "  import: 'default',",
    '})',
    '',
    `const CDN = 'https://maplestory.io/api/${REGION}/${VERSION}/item'`,
    '',
    'const iconFor = (id) => icons[`../assets/items/${id}.png`] ?? `${CDN}/${id}/icon`',
    '',
    'const RAW_GROUPS = [',
  ]

  for (const group of groups) {
    lines.push('  {')
    lines.push(`    id: '${group.id}',`)
    lines.push(`    label: '${group.label}',`)
    lines.push('    items: [')
    for (const item of group.items) {
      const cap = item.maxStar ? `, maxStar: ${item.maxStar}` : ''
      lines.push(
        `      { id: ${item.id}, name: ${JSON.stringify(item.name)}, level: ${item.level}, slot: ${JSON.stringify(item.slot)}${cap} },`,
      )
    }
    lines.push('    ],')
    lines.push('  },')
  }

  lines.push(']')
  lines.push('')
  lines.push('export const ITEM_GROUPS = RAW_GROUPS.map((group) => ({')
  lines.push('  ...group,')
  lines.push('  items: group.items.map((item) => ({ ...item, icon: iconFor(item.id) })),')
  lines.push('}))')
  lines.push('')
  lines.push('export const ITEMS = ITEM_GROUPS.flatMap((group) => group.items)')
  lines.push('')
  lines.push('const BY_ID = new Map(ITEMS.map((item) => [item.id, item]))')
  lines.push('')
  lines.push('export const findItemById = (id) => BY_ID.get(id)')
  lines.push('')

  return lines.join('\n')
}

await mkdir(ICON_DIR, { recursive: true })

const resolved = []
for (const group of GROUPS) {
  const items = []
  for (const name of group.items) {
    const item = await findItem(name)
    await downloadIcon(item.id)
    items.push(item)
    console.log(`  ${group.label.padEnd(18)} lv${String(item.level).padStart(3)}  ${item.name}`)
  }
  resolved.push({ ...group, items })
}

await writeFile(OUT_FILE, emitModule(resolved))

const total = resolved.reduce((sum, group) => sum + group.items.length, 0)
console.log(`\nWrote ${total} items to src/starforce/items.js`)
